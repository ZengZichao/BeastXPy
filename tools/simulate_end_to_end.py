#!/usr/bin/env python3
"""End-to-end simulated validation: known truth in, posterior out.

Two studies share one harness:

``--study strict`` (default)
    The original four-taxon JC69 / strict-clock check: simulate on a known
    rooted tree, run BEAST through BeastXPy, and test whether the 95% HPD of
    the root height contains the true 0.10.

``--study recovery``
    A parameter-recovery study on an eight-taxon tree simulated under an
    uncorrelated lognormal clock.  It reports, per seed and in aggregate:

    * recovery of ``ucld.stdev`` (truth known; HPD coverage and error),
    * calibration-age coverage (root prior normal(1.05, 0.15), true age 1.0),
    * topology accuracy (posterior support of every true clade and ASDSF),
    * ESS for the estimated clock and root-height parameters.

    The defaults are four seeds, 2,000 sites and 1,000,000 MCMC steps.  Use
    ``--chain-length``/``--sites`` to run a shorter pilot, and repeat
    ``--stdev-truth`` to study more than one true relaxed-clock variance.

This script is deliberately **not** part of ``pytest``: it needs a native
hmsbeagle library and real MCMC runs.  Run it manually (and record the output
in a paper's validation table):

    export BEASTX_BEAGLE_10_5_0_LIB=/path/to/libhmsbeagle
    export LD_LIBRARY_PATH="$BEASTX_BEAGLE_10_5_0_LIB:$LD_LIBRARY_PATH"
    python tools/simulate_end_to_end.py --study recovery \
        --out validation_runs/recovery --seeds 1,2,3,4

All data are generated by this script; no empirical data are used.

Exit codes: 0 = every run completed, 1 = a run failed, 2 = missing
environment.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import sys
import time
from pathlib import Path
from typing import Any, Dict, Iterable, List, Tuple

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from beastxpy.assessment import assess_workdir  # noqa: E402
from beastxpy.runner import BeastRunner, RunError  # noqa: E402
from beastxpy.treetools import TreeToolsError, clade_statistics, parse_nexus_trees  # noqa: E402

TRUE_ROOT_HEIGHT = 0.10
RECOVERY_TRUE_ROOT = 1.0

#: Eight-taxon fixed tree: ``(parent, child, duration)``; tip ages are zero.
RECOVERY_EDGES: Tuple[Tuple[str, str, float], ...] = (
    ("ROOT", "I1", 0.45),
    ("ROOT", "I2", 0.50),
    ("I1", "I3", 0.25),
    ("I1", "I4", 0.30),
    ("I2", "I5", 0.22),
    ("I2", "I6", 0.30),
    ("I3", "A", 0.30),
    ("I3", "B", 0.30),
    ("I4", "C", 0.25),
    ("I4", "D", 0.25),
    ("I5", "E", 0.28),
    ("I5", "F", 0.28),
    ("I6", "G", 0.20),
    ("I6", "H", 0.20),
)
RECOVERY_TIPS = tuple("ABCDEFGH")
#: True clades (excluding tips and the root) implied by RECOVERY_EDGES.
RECOVERY_TRUE_CLADES = [
    frozenset({"A", "B"}),
    frozenset({"C", "D"}),
    frozenset({"E", "F"}),
    frozenset({"G", "H"}),
    frozenset({"A", "B", "C", "D"}),
    frozenset({"E", "F", "G", "H"}),
]


# ---------------------------------------------------------------------------
# simulation
# ---------------------------------------------------------------------------
def simulate_alignment(path: Path, sites: int, seed: int) -> None:
    """Simulate JC69 sequences on the known four-taxon tree (strict study)."""
    rng = np.random.default_rng(seed)
    parents = {
        "A": ("I1", 0.03),
        "B": ("I1", 0.05),
        "C": ("I2", 0.05),
        "D": ("I2", 0.05),
        "I1": ("ROOT", 0.05),
        "I2": ("ROOT", 0.05),
    }

    def evolve(state: int, distance: float) -> int:
        change = 0.75 * (1.0 - np.exp(-4.0 * distance / 3.0))
        if rng.random() < change:
            return int(rng.choice([base for base in range(4) if base != state]))
        return state

    bases = "ACGT"
    sequences = {tip: [] for tip in ("A", "B", "C", "D")}
    for _ in range(sites):
        states = {"ROOT": int(rng.integers(0, 4))}
        for node in ("I1", "I2", "A", "B", "C", "D"):
            parent, distance = parents[node]
            states[node] = evolve(states[parent], distance)
        for tip in sequences:
            sequences[tip].append(bases[states[tip]])
    _write_fasta(path, sequences)


def _write_fasta(path: Path, sequences: Dict[str, List[str]]) -> None:
    fasta = "".join(f">{tip}\n{''.join(sequence)}\n" for tip, sequence in sequences.items())
    path.write_text(fasta, encoding="utf-8")


def _evolve(rng: np.random.Generator, state: int, distance: float) -> int:
    change = 0.75 * (1.0 - np.exp(-4.0 * distance / 3.0))
    if rng.random() < change:
        return int(rng.choice([base for base in range(4) if base != state]))
    return state


def simulate_recovery_alignment(
    path: Path, sites: int, seed: int, stdev_truth: float
) -> Dict[str, float]:
    """Simulate the eight-taxon tree under a lognormal relaxed clock."""
    rng = np.random.default_rng(seed)
    log_sd = float(stdev_truth)
    log_mean = -0.5 * log_sd**2  # rate mean = 1.0
    rates = {
        child: float(rng.lognormal(log_mean, log_sd))
        for _parent, child, _duration in RECOVERY_EDGES
    }
    # Normalise the realised *time-weighted* rate to 1.  Root age is informed
    # by the total substitutions along the tree (sum rate_i * duration_i), not
    # by the unweighted mean of 13 lognormal draws.  Without this correction,
    # sampling error in the rate draw shifts the root-age estimate even when
    # the inference model is correct.
    total_time = sum(duration for _parent, _child, duration in RECOVERY_EDGES)
    weighted_mean = (
        sum(rates[child] * duration for _parent, child, duration in RECOVERY_EDGES) / total_time
    )
    rates = {child: value / weighted_mean for child, value in rates.items()}
    sequences: Dict[str, List[str]] = {tip: [] for tip in RECOVERY_TIPS}
    bases = "ACGT"
    for _ in range(sites):
        states = {"ROOT": int(rng.integers(0, 4))}
        for parent, child, duration in RECOVERY_EDGES:
            states[child] = _evolve(rng, states[parent], duration * rates[child])
        for tip in RECOVERY_TIPS:
            sequences[tip].append(bases[states[tip]])
    _write_fasta(path, sequences)
    return {"rate_mean": float(np.mean(list(rates.values()))), "rates": rates}


