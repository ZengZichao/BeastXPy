"""GMRF Bayesian skyride tree prior (C08) for BEAST 1.10.4 / 10.5.0.

The plugin replaces the core coalescent/speciation tree prior with
``<gmrfSkyrideLikelihood>`` as generated by BEAUti's "GMRF Bayesian Skyride"
tree prior:

* ``skyride.popSize``   - log population sizes, one per coalescent interval
* ``skyride.groupSize`` - number of intervals grouped at each control point
* ``skyride.precision`` - GMRF smoothing precision (Gamma(0.001, 1000) prior)

Operators: ``gmrfBlockUpdateOperator``.  The GMRF likelihood is placed in the
prior (it is a tree prior, not a data likelihood) exactly as in the official
``GMRFBayesianSkyride+strict.xml`` example.
"""

from __future__ import annotations

from typing import Any, Dict, List

from ..model import ModelAssemblyError, el, param_node
from . import find_all

ANALYSIS_TYPES = ("skyride",)

_TREE_PRIOR_TAGS = {
    "yuleModel",
    "birthDeathModel",
    "birthDeathSkyline",
    "speciationLikelihood",
    "coalescentLikelihood",
    "generalizedSkyLineLikelihood",
    "gmrfSkyrideLikelihood",
    "exponentialGrowth",
    "logisticGrowth",
    "expansion",
}

_TREE_PRIOR_REFS = {
    "speciationLikelihood",
    "coalescentLikelihood",
    "generalizedSkyLineLikelihood",
    "gmrfSkyrideLikelihood",
    "gmrfSkyLineLikelihood",
}


def validate(raw: Dict[str, Any], errors: List[str]) -> None:
    groups = raw.get("population_sizes")
    if groups is not None:
        if isinstance(groups, bool) or not isinstance(groups, int) or groups < 1:
            errors.append(
                "analysis.population_sizes: must be a positive integer "
                "(number of GMRF control points)"
            )
    precision = raw.get("precision")
    if precision is not None:
        if isinstance(precision, bool) or not isinstance(precision, (int, float)):
            errors.append("analysis.precision: must be a positive number")
        elif float(precision) <= 0.0:
            errors.append("analysis.precision: must be > 0")
    if raw.get("time_aware_smoothing") not in (None, True, False):
        errors.append("analysis.time_aware_smoothing: must be true or false")


def _top_level(root: Dict[str, Any], tag: str) -> List[Dict[str, Any]]:
    return [c for c in root.get("children", []) if isinstance(c, dict) and c.get("tag") == tag]


def _node_by_id(root: Dict[str, Any], tag: str, node_id: str) -> Dict[str, Any]:
    for node in find_all(root, tag):
        if (node.get("attrib") or {}).get("id") == node_id:
            return node
    raise ModelAssemblyError(f"cannot locate <{tag} id={node_id!r}>")


def _declared_parameter_ids(root: Dict[str, Any]) -> set:
    ids = set()
    for node in find_all(root, "parameter"):
        node_id = (node.get("attrib") or {}).get("id")
        if node_id:
            ids.add(str(node_id))
    return ids


def _references_missing_parameter(node: Dict[str, Any], declared: set) -> bool:
    stack = [node]
    while stack:
        current = stack.pop()
        attrib = current.get("attrib") or {}
        if current.get("tag") == "parameter" and "idref" in attrib:
            if str(attrib["idref"]) not in declared:
                return True
        stack.extend(current.get("children") or [])
    return False


def _prune_missing_parameter_refs(root: Dict[str, Any]) -> None:
    declared = _declared_parameter_ids(root)
    operators = _node_by_id(root, "operators", "operators")
    operators["children"] = [
        node
        for node in operators.get("children", [])
        if not _references_missing_parameter(node, declared)
    ]
    prior = _node_by_id(root, "prior", "prior")
    prior["children"] = [
        node
        for node in prior.get("children", [])
        if not _references_missing_parameter(node, declared)
    ]
    for log in find_all(root, "log"):
        log["children"] = [
            node
            for node in log.get("children", [])
            if not _references_missing_parameter(node, declared)
        ]


def _remove_tree_prior(root: Dict[str, Any]) -> None:
    def is_tree_prior(node: Dict[str, Any]) -> bool:
        tag = node.get("tag")
        if tag not in _TREE_PRIOR_TAGS:
            return False
        if tag == "constantSize":
            return (node.get("attrib") or {}).get("id") == "constant"
        return True

    root["children"] = [
        node
        for node in root.get("children", [])
        if not (isinstance(node, dict) and is_tree_prior(node))
    ]
    prior = _node_by_id(root, "prior", "prior")
    prior["children"] = [
        node
        for node in prior.get("children", [])
        if not (node.get("tag") in _TREE_PRIOR_REFS or (node.get("tag") in _TREE_PRIOR_TAGS))
    ]
    for log in find_all(root, "log"):
        log["children"] = [
            node for node in log.get("children", []) if node.get("tag") not in _TREE_PRIOR_REFS
        ]


def _log_column(label: str, child_tag: str, idref: str, dp: str = "6") -> Dict[str, Any]:
    return el(
        "column",
        attrib={"label": label, "sf": dp, "width": "12"},
        children=[el(child_tag, attrib={"idref": idref})],
    )


def apply(
    root: Dict[str, Any], analysis: Dict[str, Any], config: Any, assembler: Any
) -> Dict[str, Any]:
    if len(config.partitions) != 1:
        raise ModelAssemblyError("analysis.type 'skyride' currently requires exactly one partition")
    n_taxa = len(assembler.taxa_by_name)
    dim = analysis.get("population_sizes")
    dim = int(dim) if isinstance(dim, int) and not isinstance(dim, bool) else n_taxa - 1
    if n_taxa < 2:
        raise ModelAssemblyError("skyride requires at least two taxa")
    required = n_taxa - 1
    if dim != required:
        raise ModelAssemblyError(
            f"analysis.population_sizes={dim} cannot be used: BEAST's "
            "GMRFSkyrideLikelihood requires populationSizes to have exactly "
            f"one entry per coalescent interval ({n_taxa} taxa -> {required}); "
            "omit population_sizes to use the required dimension"
        )
    precision = float(analysis.get("precision", 1.0))
    time_aware = bool(analysis.get("time_aware_smoothing", False))

    _remove_tree_prior(root)

    pop_values = " ".join("1.0" for _ in range(dim))
    skyride = el(
        "gmrfSkyrideLikelihood",
        attrib={
            "id": "skyride",
            "timeAwareSmoothing": "true" if time_aware else "false",
            "randomizeTree": "false",
        },
        children=[
            el(
                "populationSizes",
                children=[
                    param_node(
                        "skyride.popSize",
                        pop_values,
                        lower=-1e6,
                        upper=1e6,
                        dimension=dim,
                        estimate=True,
                    )
                ],
            ),
            el(
                "groupSizes",
                children=[param_node("skyride.groupSize", dimension=dim, estimate=True)],
            ),
            el(
                "precisionParameter",
                children=[
                    param_node("skyride.precision", precision, lower=0.0, upper=None, estimate=True)
                ],
            ),
            el("populationTree", children=[el("treeModel", attrib={"idref": "treeModel"})]),
        ],
    )

    tree_model = next(iter(_top_level(root, "treeModel")), None)
    if tree_model is None:
        raise ModelAssemblyError("assembled XML has no top-level <treeModel>")
    children = root.setdefault("children", [])
    children.insert(children.index(tree_model) + 1, skyride)

    prior = _node_by_id(root, "prior", "prior")
    prior.setdefault("children", []).append(
        el(
            "gammaPrior",
            attrib={"shape": "0.001", "scale": "1000.0", "offset": "0.0"},
            children=[el("parameter", attrib={"idref": "skyride.precision"})],
        )
    )
    prior["children"].append(el("gmrfSkyrideLikelihood", attrib={"idref": "skyride"}))

    operators = _node_by_id(root, "operators", "operators")
    operators.setdefault("children", []).append(
        el(
            "gmrfBlockUpdateOperator",
            attrib={"scaleFactor": "2.0", "weight": "2"},
            children=[el("gmrfSkyrideLikelihood", attrib={"idref": "skyride"})],
        )
    )

    for log_id in ("screenLog", "fileLog"):
        for log in find_all(root, "log"):
            if (log.get("attrib") or {}).get("id") != log_id:
                continue
            log.setdefault("children", []).extend(
                [
                    _log_column("skyride.popSize", "parameter", "skyride.popSize"),
                    _log_column("skyride.groupSize", "parameter", "skyride.groupSize"),
                    _log_column("skyride.precision", "parameter", "skyride.precision"),
                    _log_column("skyride", "gmrfSkyrideLikelihood", "skyride"),
                ]
            )

    _prune_missing_parameter_refs(root)
    return root
