def _require_number(raw: Dict[str, Any], key: str, errors: List[str]) -> None:
    value = raw.get(key)
    if value is None:
        return
    if isinstance(value, dict):
        value = value.get("value")
        if value is None:
            return
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        errors.append(f"analysis.{key}: must be a number, got {value!r}")
    elif float(value) <= 0.0:
        errors.append(f"analysis.{key}: must be > 0, got {value!r}")


def validate(raw: Dict[str, Any], errors: List[str]) -> None:
    """Gate-0 validation shared by the codon and SRD06 analyses."""
    analysis_type = str(raw.get("type", ""))
    genetic_code = str(raw.get("genetic_code", "universal")).strip().lower()
    if genetic_code not in GENETIC_CODES:
        errors.append(
            f"analysis.genetic_code: unknown {genetic_code!r}; choose one of "
            + ", ".join(sorted(GENETIC_CODES))
        )
    elif genetic_code != "universal":
        errors.append(
            'analysis.genetic_code: BEAST\'s <convert dataType="codon"> parser '
            "only supports the universal code; non-universal codes cannot be "
            "applied to the alignment"
        )
    _require_number(raw, "omega", errors)
    _require_number(raw, "kappa", errors)
    if analysis_type == "codon":
        errors.append(
            "analysis.type 'codon': BEAST 1.10.4 and 10.5.0 cannot apply "
            '<convert dataType="codon">. Two independent upstream defects: '
            "(1) ConvertAlignmentParser's syntax rule rejects geneticCode "
            "('Unhandled attribute (typo?) geneticCode'); (2) without that "
            "attribute DataTypeUtils cannot resolve plain 'codon' because only "
            "'codon-<geneticCode>' is registered (1.10.4: 'Incompatible "
            "alignment DataType'; 10.5.0: NullPointerException in "
            "DataType.getDescription). Official testCodonLikelihood.xml fails "
            "identically. Use 'srd06', or a BEAST build whose parser accepts "
            "codon-<geneticCode>; no legacy shim is enabled by default."
        )
    if analysis_type == "srd06":
        for key in ("omega",):
            if key in raw:
                errors.append(
                    f"analysis.{key}: is only used by analysis.type 'codon', " "not by 'srd06'"
                )
        partitions = raw.get("partitions")
        if partitions is not None and partitions != ["CP1+2", "CP3"]:
            errors.append(
                "analysis.partitions: SRD06 is fixed to ['CP1+2', 'CP3'] "
                "(first+second versus third codon positions)"
            )


def _check_nucleotide_partition(config: Any, analysis_type: str) -> Any:
    if len(config.partitions) != 1:
        raise ModelAssemblyError(
            f"analysis.type {analysis_type!r} currently requires exactly one "
            f"partition (got {len(config.partitions)})"
        )
    partition = config.partitions[0]
    data_type = getattr(partition.alignment, "data_type", None)
    value = getattr(data_type, "value", data_type)
    if str(value) != "nucleotide":
        raise ModelAssemblyError(
            f"analysis.type {analysis_type!r} requires a nucleotide alignment "
            f"(got {value!r}); BEAST builds the codon alignment with <convert>"
        )
    return partition


def _insert_after(root: Dict[str, Any], anchor: Dict[str, Any], node: Dict[str, Any]) -> None:
    children = root.setdefault("children", [])
    try:
        index = children.index(anchor)
    except ValueError as exc:  # pragma: no cover - defensive
        raise ModelAssemblyError(f"cannot locate anchor <{anchor.get('tag')}>") from exc
    children.insert(index + 1, node)


def _equal_frequencies(dimension: int) -> str:
    """Return a simplex vector of length ``dimension`` summing to 1.0."""
    unit = 0.25 if dimension == 4 else 1.0 / dimension
    values = [round(unit, 12) for _ in range(dimension)]
    values[-1] = round(1.0 - sum(values[:-1]), 12)
    return " ".join(f"{value:.12g}" for value in values)


def _top_level(root: Dict[str, Any], tag: str) -> List[Dict[str, Any]]:
    return [c for c in root.get("children", []) if isinstance(c, dict) and c.get("tag") == tag]


def _top_by_id(root: Dict[str, Any], tag: str, node_id: str) -> Dict[str, Any]:
    for node in _top_level(root, tag):
        if (node.get("attrib") or {}).get("id") == node_id:
            return node
    raise ModelAssemblyError(f"cannot locate top-level <{tag} id={node_id!r}>")


def _replace_top_level(
    root: Dict[str, Any], old: Dict[str, Any], new: List[Dict[str, Any]]
) -> None:
    children = root.setdefault("children", [])
    index = children.index(old)
    children[index : index + 1] = new


def _parameter_by_id(root: Dict[str, Any], pid: str) -> Dict[str, Any]:
    for node in find_all(root, "parameter"):
        if (node.get("attrib") or {}).get("id") == pid:
            return node
    raise ModelAssemblyError(f"cannot locate emitted parameter {pid!r}")


def _operator_nodes(root: Dict[str, Any]) -> List[Dict[str, Any]]:
    operators = _node_by_id(root, "operators", "operators")
    return operators.setdefault("children", [])


def _node_by_id(root: Dict[str, Any], tag: str, node_id: str) -> Dict[str, Any]:
    for node in find_all(root, tag):
        if (node.get("attrib") or {}).get("id") == node_id:
            return node
    raise ModelAssemblyError(f"cannot locate <{tag} id={node_id!r}>")


def _prior_nodes(root: Dict[str, Any]) -> List[Dict[str, Any]]:
    prior = _node_by_id(root, "prior", "prior")
    return prior.setdefault("children", [])


def _append_log_column(root: Dict[str, Any], log_id: str, column: Dict[str, Any]) -> None:
    for candidate in find_all(root, "log"):
        if (candidate.get("attrib") or {}).get("id") == log_id:
            candidate.setdefault("children", []).append(column)
            return


def _positive_operator(pid: str, weight: str = "1", window: str = "0.5") -> Dict[str, Any]:
    """Random-walk move for a parameter with finite upper bounds."""
    return el(
        "randomWalkOperator",
        attrib={"windowSize": window, "weight": weight},
        children=[el("parameter", attrib={"idref": pid})],
    )


def _codon_parameters(raw: Dict[str, Any]) -> Dict[str, Any]:
    omega_raw = raw.get("omega", 1.0)
    if isinstance(omega_raw, dict):
        omega = float(omega_raw.get("value", 1.0))
        lower = float(omega_raw.get("lower", 0.0))
        upper = float(omega_raw.get("upper", 100.0))
    else:
        omega = float(omega_raw)
        lower, upper = 0.0, 100.0
    genetic_code = str(raw.get("genetic_code", "universal")).strip().lower()
    return {
        "omega": omega,
        "omega_lower": lower,
        "omega_upper": upper,
        "genetic_code": GENETIC_CODE_BEAST_NAMES.get(genetic_code, genetic_code),
    }


def _apply_codon(root: Dict[str, Any], analysis: Dict[str, Any], config: Any) -> Dict[str, Any]:
    partition = _check_nucleotide_partition(config, "codon")
    settings = _codon_parameters(analysis)
    genetic_code = settings["genetic_code"]
    alignment_id = partition.alignment.id

    alignment = _top_by_id(root, "alignment", alignment_id)
    # BEAST 1.10.4/10.5.0 ConvertAlignmentParser resolves codon-universal
    # through DataTypeUtils but its syntax rule still lists only "codon"; the
    # validator therefore runs this fixture with --relaxed.
    convert = el(
        "convert",
        attrib={"id": "codonAlignment", "dataType": "codon-universal"},
        children=[el("alignment", attrib={"idref": alignment_id})],
    )
    _insert_after(root, alignment, convert)

    # Codon patterns replace the nucleotide patterns in place (same id).
    patterns = next(
        (
            node
            for node in _top_level(root, "patterns")
            if (node.get("attrib") or {}).get("id") == "patterns"
        ),
        None,
    )
    if patterns is None:
        raise ModelAssemblyError("cannot locate the emitted top-level <patterns>")
    patterns["attrib"] = {"id": "patterns", "from": "1"}
    patterns["children"] = [el("alignment", attrib={"idref": "codonAlignment"})]

    site_model = next(iter(_top_level(root, "siteModel")), None)
    if site_model is None:
        raise ModelAssemblyError("cannot locate the emitted top-level <siteModel>")

    hky = next((node for node in _top_level(root, "HKYModel")), None)
    if hky is None:
        raise ModelAssemblyError("codon analysis expects the core HKYModel fragment")
    kappa = None
    for child in hky.get("children") or []:
        if child.get("tag") == "kappa":
            kappa = child
            break
    if kappa is None:
        raise ModelAssemblyError("the core HKYModel fragment has no <kappa>")
    # Detach kappa before dropping the HKY model so its parameter survives.
    hky["children"] = [child for child in hky.get("children", []) if child is not kappa]
    _replace_top_level(root, hky, [])

    frequency_model = el(
        "frequencyModel",
        attrib={"id": "codonFreq", "dataType": f"codon-{genetic_code}"},
        children=[
            el("alignment", attrib={"idref": "codonAlignment"}),
            el(
                "frequencies",
                children=[param_node("frequencies", _equal_frequencies(61), dimension=61)],
            ),
        ],
    )
    yang = el(
        "yangCodonModel",
        attrib={"id": "yang", "geneticCode": genetic_code},
        children=[
            el("frequencyModel", attrib={"idref": "codonFreq"}),
            el(
                "omega",
                children=[
                    param_node(
                        "omega",
                        settings["omega"],
                        lower=settings["omega_lower"],
                        upper=settings["omega_upper"],
                        estimate=True,
                    )
                ],
            ),
            kappa,
        ],
    )
    # The codon model and its frequency model must precede the site model.
    children = root.setdefault("children", [])
    site_index = children.index(site_model)
    children[site_index:site_index] = [frequency_model, yang]

    substitution = find_one(site_model, "substitutionModel")
    if substitution is None:
        raise ModelAssemblyError("the emitted <siteModel> has no <substitutionModel>")
    substitution["children"] = [el("yangCodonModel", attrib={"idref": "yang"})]

    _operator_nodes(root).append(_positive_operator("omega", weight="2", window="0.1"))
    _prior_nodes(root).append(
        el(
            "logNormalPrior",
            attrib={"mean": "1.0", "stdev": "1.25", "offset": "0.0", "meanInRealSpace": "false"},
            children=[el("parameter", attrib={"idref": "omega"})],
        )
    )
    _append_log_column(
        root,
        "fileLog",
        el(
            "column",
            attrib={"label": "omega", "sf": "6", "width": "12"},
            children=[el("parameter", attrib={"idref": "omega"})],
        ),
    )
    # Keep the original HKY parameters used by the codon model in the trace.
    return root


def _hky_model(model_id: str, prefix: str) -> Dict[str, Any]:
    return el(
        "HKYModel",
        attrib={"id": model_id},
        children=[
            el(
                "frequencies",
                children=[
                    el(
                        "frequencyModel",
                        attrib={"dataType": "nucleotide"},
                        children=[
                            el(
                                "frequencies",
                                children=[
                                    param_node(
                                        f"{prefix}frequencies",
                                        _equal_frequencies(4),
                                        dimension=4,
                                    )
                                ],
                            )
                        ],
                    )
                ],
            ),
            el(
                "kappa",
                children=[param_node(f"{prefix}kappa", 2.0, lower=0.0, upper=100.0, estimate=True)],
            ),
        ],
    )


def _apply_srd06(root: Dict[str, Any], analysis: Dict[str, Any], config: Any) -> Dict[str, Any]:
    partition = _check_nucleotide_partition(config, "srd06")
    alignment_id = partition.alignment.id

    patterns = next(
        (
            node
            for node in _top_level(root, "patterns")
            if (node.get("attrib") or {}).get("id") == "patterns"
        ),
        None,
    )
    if patterns is None:
        raise ModelAssemblyError("cannot locate the emitted top-level <patterns>")
    merge_12 = el(
        "mergePatterns",
        attrib={"id": "CP1+2.patterns"},
        children=[
            el(
                "patterns",
                attrib={"from": "1", "every": "3"},
                children=[el("alignment", attrib={"idref": alignment_id})],
            ),
            el(
                "patterns",
                attrib={"from": "2", "every": "3"},
                children=[el("alignment", attrib={"idref": alignment_id})],
            ),
        ],
    )
    merge_3 = el(
        "mergePatterns",
        attrib={"id": "CP3.patterns"},
        children=[
            el(
                "patterns",
                attrib={"from": "3", "every": "3"},
                children=[el("alignment", attrib={"idref": alignment_id})],
            ),
        ],
    )
    _replace_top_level(root, patterns, [merge_12, merge_3])

    # The core HKY/site model become the CP1+2 partition.
    hky = next((node for node in _top_level(root, "HKYModel")), None)
    site_model = next(iter(_top_level(root, "siteModel")), None)
    tree_likelihood = next(iter(_top_level(root, "treeLikelihood")), None)
    if hky is None or site_model is None or tree_likelihood is None:
        raise ModelAssemblyError("SRD06 analysis expects the core HKY/site/likelihood fragments")
    hky["attrib"]["id"] = "CP1+2.hky"
    site_model["attrib"]["id"] = "CP1+2.siteModel"
    substitution = find_one(site_model, "substitutionModel")
    if substitution is None:
        raise ModelAssemblyError("the emitted <siteModel> has no <substitutionModel>")
    substitution["children"] = [el("HKYModel", attrib={"idref": "CP1+2.hky"})]
    tree_likelihood["attrib"]["id"] = "CP1+2.treeLikelihood"
    for child in tree_likelihood.get("children") or []:
        if child.get("tag") == "patterns":
            child["attrib"] = {"idref": "CP1+2.patterns"}
        elif child.get("tag") == "siteModel":
            child["attrib"] = {"idref": "CP1+2.siteModel"}

    # Independent third-position HKY model.
    cp3_hky = _hky_model("CP3.hky", "CP3.")
    cp3_site = el(
        "siteModel",
        attrib={"id": "CP3.siteModel"},
        children=[el("substitutionModel", children=[el("HKYModel", attrib={"idref": "CP3.hky"})])],
    )
    cp3_likelihood = el(
        "treeLikelihood",
        attrib={"id": "CP3.treeLikelihood"},
        children=[
            el("patterns", attrib={"idref": "CP3.patterns"}),
            el("treeModel", attrib={"idref": "treeModel"}),
            el("siteModel", attrib={"idref": "CP3.siteModel"}),
            el("strictClockBranchRates", attrib={"idref": "branchRates"}),
        ],
    )
    children = root.setdefault("children", [])
    index = children.index(site_model)
    children[index + 1 : index + 1] = [cp3_hky, cp3_site]
    clock = next(iter(_top_level(root, "strictClockBranchRates")), None)
    if clock is None:
        raise ModelAssemblyError("SRD06 analysis expects a strictClockBranchRates fragment")
    children.insert(children.index(clock) + 1, cp3_likelihood)

    # Likelihood wrapper must contain both partitions; the core entry still
    # points at the old id.
    likelihood = _node_by_id(root, "likelihood", "likelihood")
    for child in likelihood.get("children") or []:
        if (
            child.get("tag") == "treeLikelihood"
            and (child.get("attrib") or {}).get("idref") == "treeLikelihood"
        ):
            child["attrib"]["idref"] = "CP1+2.treeLikelihood"
    likelihood.setdefault("children", []).append(
        el("treeLikelihood", attrib={"idref": "CP3.treeLikelihood"})
    )

    for pid, weight in (("CP3.kappa", "1"),):
        _operator_nodes(root).append(_positive_operator(pid, weight=weight))
    _operator_nodes(root).append(
        el(
            "deltaExchange",
            attrib={"delta": "0.01", "weight": "1"},
            children=[el("parameter", attrib={"idref": "CP3.frequencies"})],
        )
    )
    _prior_nodes(root).append(
        el(
            "uniformPrior",
            attrib={"lower": "0.0", "upper": "1.0"},
            children=[el("parameter", attrib={"idref": "CP3.frequencies"})],
        )
    )
    _prior_nodes(root).append(
        el(
            "logNormalPrior",
            attrib={"mean": "1.0", "stdev": "1.25", "offset": "0.0", "meanInRealSpace": "false"},
            children=[el("parameter", attrib={"idref": "CP3.kappa"})],
        )
    )
    for pid in ("CP3.kappa", "CP3.frequencies"):
        _append_log_column(
            root,
            "fileLog",
            el(
                "column",
                attrib={"label": pid, "sf": "6", "width": "12"},
                children=[el("parameter", attrib={"idref": pid})],
            ),
        )
    return root


def apply(
    root: Dict[str, Any], analysis: Dict[str, Any], config: Any, assembler: Any
) -> Dict[str, Any]:
    analysis_type = str(analysis.get("type"))
    if analysis_type == "codon":
        return _apply_codon(root, analysis, config)
    if analysis_type == "srd06":
        return _apply_srd06(root, analysis, config)
    raise ModelAssemblyError(f"codon plugin cannot handle analysis type {analysis_type!r}")
