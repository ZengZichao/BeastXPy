"""Codon (Yang GY94) and SRD06 coverage analyses (C07).

Both analyses start from a *nucleotide* alignment because BEAST 1 reads the
raw codon triplets through ``<convert dataType="codon">``.  The plugin:

* ``codon``  - replaces the nucleotide substitution model with
  ``yangCodonModel`` (K80 transition/transversion ratio + dN/dS omega) and a
  61-dimensional codon frequency model;
* ``srd06``  - splits the alignment into the first+second and third codon
  positions (``mergePatterns``) and fits an independent HKY model to each
  partition, i.e. the classic SRD06 codon-position partition model.

The plugin deliberately reuses the emitted ``kappa``/``frequencies``
parameters of the core HKY model where possible so that the operators, priors
and log columns generated by :class:`beastxpy.model.ModelAssembler` remain
valid.
"""

from __future__ import annotations

from typing import Any, Dict, List

from ..model import ModelAssemblyError, el, param_node
from . import find_all, find_one

ANALYSIS_TYPES = ("codon", "srd06")

#: Genetic codes accepted by ``<convert dataType="codon">`` and
#: ``yangCodonModel``.  The plugin accepts the human-readable snake_case
